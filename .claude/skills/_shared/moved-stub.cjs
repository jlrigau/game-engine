#!/usr/bin/env node
/*
 * moved-stub — the page to leave at a game's OLD address when the game moves (new domain,
 * new GitHub owner…), so players keep their progress and find the game again.
 *
 * Saves (localStorage) and home-screen apps belong to the address, so the new site starts
 * empty. This page, served at the old address, reads the player's save THERE and opens the
 * new address with it in the URL fragment (#handover=…); the engine imports it on arrival
 * (never overwriting an existing save — see ENGINE.md "Moving a game to a new address").
 *  - in a browser tab: it continues by itself after a short moment (or on tap);
 *  - in a home-screen app: it stays and explains, in two big steps, how to open the game and
 *    add its new icon (iOS gives every home-screen app its own storage, so the hand-over must
 *    start from the old icon the child actually plays with).
 *
 *   node .claude/skills/_shared/moved-stub.cjs --from <game repo dir> --to <new URL> --out <dir> [--lang fr|en]
 *
 * --from  reads game.config.js (title, saveKey, legacySave keys), manifest.webmanifest and the app
 *         icons, which are copied so the old home-screen icon keeps looking the same.
 * --out   a folder to publish at the old address (e.g. a repo with the game's old name).
 */
const fs = require("node:fs"), path = require("node:path");
const arg = (n, d) => { const i = process.argv.indexOf(n); return i >= 0 && process.argv[i + 1] ? process.argv[i + 1] : d; };
const from = arg("--from"), to = arg("--to"), out = arg("--out"), lang = arg("--lang", "fr");
if (!from || !to || !out) { console.error("usage: moved-stub.cjs --from <game dir> --to <new URL> --out <dir> [--lang fr|en]"); process.exit(1); }
if (!/^https:\/\//.test(to) && !/^http:\/\/(localhost|127\.0\.0\.1)[:/]/.test(to)) { console.error("--to must be an https:// URL (http://localhost only for tests)"); process.exit(1); }

// Read the game's config in a sandbox (it only assigns window.GAME).
const window = {};
new Function("window", fs.readFileSync(path.join(from, "game.config.js"), "utf8"))(window);
const G = window.GAME, M = G.meta || {};
const saveKey = M.saveKey || "generic-engine-save";
const keys = [saveKey, saveKey + ":muted"].concat(M.legacySave ? [].concat(M.legacySave.key || []) : []);
const title = M.title || "Game";
let manifest = {};
try { manifest = JSON.parse(fs.readFileSync(path.join(from, "manifest.webmanifest"), "utf8")); } catch (e) { /* optional */ }
const bg = manifest.background_color || "#fff6ec", theme = manifest.theme_color || bg;

const S = {
  fr: { moved: "Le jeu a déménagé !", saved: "Ta partie part avec toi.", go: "Continuer", wait: "Ouverture…",
    app1: "Touche « Continuer » : le jeu s'ouvre à sa nouvelle adresse, avec ta partie.",
    app2: "Ajoute-le sur l'écran d'accueil (Partager, puis « Sur l'écran d'accueil »), puis supprime cette ancienne icône.",
    none: "Aucune partie trouvée ici : tu commenceras une nouvelle partie." },
  en: { moved: "The game has moved!", saved: "Your game comes along with you.", go: "Continue", wait: "Opening…",
    app1: "Tap “Continue”: the game opens at its new address, with your game.",
    app2: "Add it to your home screen (Share, then “Add to Home Screen”), then delete this old icon.",
    none: "No saved game found here: you will start a new one." },
}[lang] || null;
if (!S) { console.error("--lang must be fr or en"); process.exit(1); }

fs.mkdirSync(out, { recursive: true });
const icons = ["apple-touch-icon.png", "icon-192.png", "icon-512.png", "icon-maskable.png", "favicon.png"];
fs.mkdirSync(path.join(out, "assets"), { recursive: true });
icons.forEach((f) => { const p = path.join(from, "assets", f); if (fs.existsSync(p)) fs.copyFileSync(p, path.join(out, "assets", f)); });
if (manifest.name) fs.writeFileSync(path.join(out, "manifest.webmanifest"), JSON.stringify(manifest, null, 2) + "\n");

const esc = (t) => String(t).replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" }[c]));
const html = `<!doctype html>
<!-- Generated by .claude/skills/_shared/moved-stub.cjs — "${esc(title)}" moved to ${esc(to)} -->
<html lang="${lang}">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<meta name="apple-mobile-web-app-capable" content="yes">
<meta name="theme-color" content="${esc(theme)}">
<title>${esc(title)}</title>
<link rel="icon" href="assets/favicon.png">
<link rel="apple-touch-icon" href="assets/apple-touch-icon.png">
${manifest.name ? '<link rel="manifest" href="manifest.webmanifest">' : ""}
<style>
  html, body { margin: 0; height: 100%; }
  body { display: grid; place-items: center; background: ${esc(bg)}; color: #2b2450; font: 18px/1.45 system-ui, -apple-system, "Segoe UI", sans-serif; padding: 24px; box-sizing: border-box; }
  .card { width: 100%; max-width: 420px; box-sizing: border-box; background: #fff; border-radius: 28px; padding: 28px 24px; text-align: center; box-shadow: 0 18px 50px rgba(43,36,80,.18); }
  .icon { width: 108px; height: 108px; border-radius: 26px; margin: 0 auto 14px; display: block; box-shadow: 0 8px 20px rgba(43,36,80,.2); }
  h1 { font-size: 26px; margin: 0 0 6px; }
  p { margin: 0 0 18px; color: #5a557a; }
  ol { text-align: left; margin: 0 0 20px; padding-left: 22px; color: #3c3762; }
  ol li { margin-bottom: 10px; }
  a.go { display: flex; align-items: center; justify-content: center; height: 56px; border-radius: 999px; background: #2b2450; color: #fff; font-weight: 700; font-size: 20px; text-decoration: none; }
  .hidden { display: none; }
</style>
</head>
<body>
<main class="card">
  <img class="icon" src="assets/apple-touch-icon.png" alt="">
  <h1>${esc(S.moved)}</h1>
  <p id="msg">${esc(S.saved)}</p>
  <ol id="steps" class="hidden"><li>${esc(S.app1)}</li><li>${esc(S.app2)}</li></ol>
  <a class="go" id="go" href="${esc(to)}">${esc(S.go)}</a>
</main>
<script>
(function () {
  var TO = ${JSON.stringify(to)}, KEYS = ${JSON.stringify(keys)}, found = {}, n = 0;
  KEYS.forEach(function (k) { try { var v = localStorage.getItem(k); if (v != null) { found[k] = v; if (k.slice(-7) !== ":muted") n++; } } catch (e) {} });
  var url = TO;
  if (n) {
    var json = JSON.stringify({ v: 1, keys: found });
    var b = btoa(unescape(encodeURIComponent(json))).replace(/\\+/g, "-").replace(/\\//g, "_").replace(/=+$/, "");
    url = TO + "#handover=" + b;
  } else {
    document.getElementById("msg").textContent = ${JSON.stringify(S.none)};
  }
  var go = document.getElementById("go"); go.href = url;
  var app = window.navigator.standalone === true || (window.matchMedia && matchMedia("(display-mode: standalone)").matches);
  if (app) { document.getElementById("steps").classList.remove("hidden"); return; }
  setTimeout(function () { go.textContent = ${JSON.stringify(S.wait)}; location.replace(url); }, 1600);
})();
</script>
</body>
</html>
`;
fs.writeFileSync(path.join(out, "index.html"), html);
console.log(`✓ ${path.join(out, "index.html")}  (${title} → ${to}; keys: ${keys.join(", ")})`);
